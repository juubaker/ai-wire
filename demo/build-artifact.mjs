/**
 * Generates demo/artifact.jsx — a single-file version of the wire that runs in
 * a Claude artifact, where there is no bundler, no filesystem and no server.
 *
 *   node demo/build-artifact.mjs
 *
 * It is GENERATED, not maintained. App.jsx stays the only copy of the UI; this
 * script inlines it along with the modules it imports, and swaps the four
 * things an artifact can't do for demo stubs:
 *
 *   storage       → in-memory (artifact localStorage is per-viewer and can throw)
 *   wire-api      → explains that checking needs the real deployment
 *   providers     → a single "Demo" entry, so the picker has something to show
 *   import.meta   → not available without a bundler
 *
 * Re-run it after changing App.jsx, check.js, seed.js or wire.css.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";

const root = process.cwd();
const out = join(root, "demo/artifact.jsx");

const read = (p) => readFile(join(root, p), "utf8");

/** Drop every import line; the demo has nothing to import from. */
const stripImports = (src) => src.replace(/^import[\s\S]*?from\s+["'][^"']+["'];?\s*$/gm, "");

/** `export const x` → `const x`, so everything lands in one module scope. */
const stripExports = (src) => src.replace(/^export\s+(const|function|default\s+function)\s/gm, "$1 ");

const banner = (title) => `\n/* ${"─".repeat(68)}\n   ${title}\n   ${"─".repeat(68)} */\n`;

/**
 * App.jsx uses a handful of Tailwind utilities for layout, and the demo has no
 * Tailwind build. Without these the status bar and the per-entry metadata row
 * collapse into run-together text — so the exact set used is shimmed here.
 *
 * Generated from a grep of App.jsx; if you add a utility class there, add it
 * here too or the demo will quietly lose that bit of layout.
 */
const TAILWIND_SHIM = `
/* layout utilities, shimmed — see demo/build-artifact.mjs */
.flex{display:flex}
.inline-block{display:inline-block}
.flex-wrap{flex-wrap:wrap}
.items-center{align-items:center}
.ml-auto{margin-left:auto}
.gap-1{gap:.25rem}
.gap-2{gap:.5rem}
.gap-x-4{column-gap:1rem}
.gap-y-2{row-gap:.5rem}
.mt-1{margin-top:.25rem}
.mt-2{margin-top:.5rem}
.mt-3{margin-top:.75rem}
.mt-8{margin-top:2rem}
.mb-7{margin-bottom:1.75rem}
.pt-4{padding-top:1rem}
.px-3{padding-left:.75rem;padding-right:.75rem}
.py-2{padding-top:.5rem;padding-bottom:.5rem}
`;

const [appSrc, checkSrc, seedSrc, cssSrc] = await Promise.all([
  read("src/App.jsx"),
  read("src/lib/check.js"),
  read("src/data/seed.js"),
  read("src/styles/wire.css"),
]);

// check.js imports JSON_ONLY and formatResults for buildPrompt, which the demo
// never calls. Stub them rather than pulling in two more modules.
const checkInlined = stripExports(stripImports(checkSrc))
  .replace(/^\s*$/gm, "")
  .trim();

const seedInlined = stripExports(stripImports(seedSrc)).trim();

let appInlined = stripImports(appSrc)
  // The component is rendered directly, not exported.
  .replace(/^export default function Wire\(\)/m, "function Wire()")
  .replace(/import\.meta\.env\.VITE_WIRE_POLL_MINUTES/g, "undefined");

// Inject the stylesheet into the component so the artifact needs no CSS file.
appInlined = appInlined.replace(
  /(\s*)<div className="wire-root">/,
  `$1<div className="wire-root">$1  <style>{WIRE_CSS}</style>`
);

const demo = `/**
 * AI Wire — single-file demo.
 *
 * GENERATED by demo/build-artifact.mjs. Do not edit: re-run the script.
 *
 * This is the real interface — sections, date and type and model filters, the
 * rail — over the seed entries, with the network and storage layers stubbed.
 * Checking for new entries needs the deployed site, which has a key and a
 * scheduled job behind it; here the button says so.
 */
import { useState, useEffect, useMemo, useRef, useCallback } from "react";

const WIRE_CSS = \`${(cssSrc + TAILWIND_SHIM).replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\`;
${banner("from src/data/seed.js")}
${seedInlined}
${banner("from src/lib/check.js")}
const JSON_ONLY = "";
const formatResults = () => "";

${checkInlined}
${banner("demo stubs — the real modules need a bundler and a server")}
/** In-memory: an artifact's localStorage belongs to one viewer and can throw. */
const memory = new Map();
const storage = {
  async get(key) {
    if (!memory.has(key)) throw new Error(\`no entry for \${key}\`);
    return { key, value: memory.get(key) };
  },
  async set(key, value) {
    memory.set(key, value);
    return { key, value };
  },
};

const PROVIDERS = [
  { id: "demo", label: "Demo", docs: "https://github.com/juubaker/ai-wire", models: ["seed entries"], supportsSearch: false },
];
const byId = () => PROVIDERS[0];
const DEFAULT_PROVIDER = "demo";
const isFeedMode = false;

async function fetchUpdates() {
  // Deliberately a thrown error rather than a silent no-op: the status line
  // then explains why nothing arrived instead of implying the wire is current.
  throw new Error(
    "this demo has no backend — the live site runs the check on a schedule"
  );
}
${banner("the app, inlined from src/App.jsx")}
${appInlined.trim()}

export default Wire;
`;

await mkdir(dirname(out), { recursive: true });
await writeFile(out, demo);

const lines = demo.split("\n").length;
console.log(`wrote demo/artifact.jsx — ${lines} lines, ${(demo.length / 1024).toFixed(1)} kB`);

// Cheap guards against the two ways this silently breaks.
const leftoverImports = demo.match(/^import .*from ["']\.\//gm);
if (leftoverImports) {
  console.error("relative imports survived:", leftoverImports);
  process.exit(1);
}
if (demo.includes("import.meta")) {
  console.error("import.meta survived — an artifact has no bundler to define it");
  process.exit(1);
}
console.log("no relative imports, no import.meta — safe to paste as an artifact");
